#!/usr/bin/env python3
"""csr_probe.py -- Sail's CSR existence rules: which of the 4096 CSR addresses an access traps on, per privilege.

Generates a probe program, builds it, runs it on Sail under several configs and prints, per config, the address
ranges that a read (csrrs rd, csr, x0) and a write of the value just read (csrrw x0, csr, rd) do NOT trap on, in M,
S and U (counteren clear, mstatus.FS Initial), the counter range 0xC00-0xC1F under four mcounteren/scounteren
settings, and a write/readback of a few CSRs. This is the oracle for erratum E10 and Zicntr
(verification/reference/README.md); csr_table.txt is its output.

Run inside WSL from the repo root:  python3 verification/reference/probes/csr_probe.py [--raw CONFIG]
"""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
SAIL = Path.home() / "sail-install" / "bin" / "sail_riscv_sim"
ACT = REPO / "verification" / "riscv-arch-test"
LOCKSTEP_OVR = [REPO / "verification" / "lockstep" / "sail_config_override.json", REPO / "verification" / "fpu" / "sail_fd_override.json"]
ZICNTR_ON = {"extensions": {"Zicntr": {"supported": True}}}

CONFIGS = {   # name: (--config file or None for Sail's default, [--config-override files], Zicntr on)
    "act-rv64im":          (ACT / "quantiumv-rv64im" / "sail.json", [], False),
    "act-rv64im+zicntr":   (ACT / "quantiumv-rv64im" / "sail.json", [], True),
    "act-fd":              (ACT / "quantiumv-rv64imafdc" / "sail.json", [], False),
    "act-fd+zicntr":       (ACT / "quantiumv-rv64imafdc" / "sail.json", [], True),
    "lockstep":            (None, LOCKSTEP_OVR, False),
    "lockstep+zicntr":     (None, LOCKSTEP_OVR, True),
}

M, S, U = 3, 1, 0
# pass id: (privilege, mcounteren, scounteren, addresses)
FULL = range(0x1000)
CNT = range(0xC00, 0xC20)
PASSES = {
    0: (M, 0, 0, FULL),
    1: (S, 0, 0, FULL),
    2: (U, 0, 0, FULL),
    3: (S, 7, 0, CNT),
    4: (U, 7, 0, CNT),
    5: (U, 7, 7, CNT),
    6: (U, 0, 7, CNT),
}
WRBACK = [0x320, 0x323, 0xB03, 0xF15, 0x747, 0x7A0, 0x7A5, 0xB00, 0xB02, 0x306, 0x106, 0x30A, 0x10A]
END_ID = 0xFFFFF


def gen():
    a = ["# generated by csr_probe.py", "    .option norvc", "    .section .text", "    .globl _start", "_start:",
         "    la      t0, trap", "    csrw    mtvec, t0",
         "    li      t0, -1", "    csrw    pmpaddr0, t0", "    li      t0, 0x1F", "    csrw    pmpcfg0, t0",
         "    li      t0, 0x2000", "    csrs    mstatus, t0"]          # FS Initial where F exists: fflags/frm/fcsr reachable
    for p, (priv, mce, sce, addrs) in PASSES.items():
        a += [f"# pass {p}: privilege {priv}, mcounteren {mce}, scounteren {sce}",
              f"    li      t0, {mce}", "    csrw    mcounteren, t0", f"    li      t0, {sce}", "    csrw    scounteren, t0"]
        if priv != M:
            a += ["    li      t0, 0x1800", "    csrc    mstatus, t0", f"    li      t0, {priv << 11}", "    csrs    mstatus, t0",
                  f"    la      t0, p{p}", "    csrw    mepc, t0", f"    la      x26, after_p{p}", "    mret"]
        a.append(f"p{p}:")
        for addr in addrs:
            pid = (p << 16) | addr
            a += [f"    li      x31, {pid:#x}", "    li      x30, 0", f"    csrrs   x30, {addr:#x}, x0",
                  f"    li      x31, {pid | 0x1000:#x}", f"    csrrw   x0, {addr:#x}, x30"]
        if priv != M:
            a += [f"    li      x31, {END_ID:#x}", "    ecall"]
        a.append(f"after_p{p}:")
    a += ["    li      t0, 0", "    csrw    mcounteren, t0", "    csrw    scounteren, t0", "# pass 7: write all ones, read back (M)"]
    for addr in WRBACK:
        pid = (7 << 16) | addr
        a += [f"    li      x31, {pid | 0x2000:#x}", "    li      t0, -1", f"    csrrw   x0, {addr:#x}, t0",
              f"    li      x31, {pid | 0x3000:#x}", "    li      x30, 0", f"    csrrs   x30, {addr:#x}, x0",
              f"    csrrw   x0, {addr:#x}, x0"]
    a += [f"    li      x31, {END_ID:#x}", "    li      t0, 1", "    la      t1, tohost", "    sd      t0, 0(t1)", "1:  j       1b",
          "# x27 = mcause and skip the instruction; an ECALL ends an S/U pass: back to M at x26",
          "    .balign 4", "trap:", "    csrr    x27, mcause", "    li      s1, 8", "    beq     x27, s1, 3f", "    li      s1, 9",
          "    beq     x27, s1, 3f", "    csrr    s1, mepc", "    addi    s1, s1, 4", "    csrw    mepc, s1", "    mret",
          "3:  csrw    mepc, x26", "    li      s1, 0x1800", "    csrs    mstatus, s1", "    mret",
          "    .section .data", "    .balign 8", "    .globl tohost", "tohost:", "    .dword 0", "    .globl fromhost", "fromhost:",
          "    .dword 0"]
    return "\n".join(a) + "\n"


def run(elf, cfg, ovr, zicntr, d):
    cmd = [str(SAIL)]
    if cfg:
        cmd += ["--config", str(cfg)]
    for o in ovr:
        cmd += ["--config-override", str(o)]
    if zicntr:
        z = Path(d) / "zicntr_on.json"
        z.write_text(json.dumps(ZICNTR_ON))
        cmd += ["--config-override", str(z)]
    cmd += ["--inst-limit=3000000", "--trace-reg", str(elf)]
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def parse(out):
    """{id: {"trap": cause or None, "val": x30 value or None}}"""
    res, cur = {}, None
    for line in out.splitlines():
        m = re.match(r"^x(\d+) <- 0x([0-9A-Fa-f]+)$", line)
        if not m:
            continue
        reg, val = int(m.group(1)), int(m.group(2), 16)
        if reg == 31:
            cur = val
            res.setdefault(cur, {"trap": None, "val": None})
        elif cur is not None and cur != END_ID and reg == 27:
            res[cur]["trap"] = val
        elif cur is not None and cur != END_ID and reg == 30:
            res[cur]["val"] = val
    return res


def ranges(addrs):
    out, start, prev = [], None, None
    for x in sorted(addrs):
        if start is None:
            start = prev = x
        elif x == prev + 1:
            prev = x
        else:
            out.append((start, prev))
            start = prev = x
    if start is not None:
        out.append((start, prev))
    return " ".join(f"{s:03x}" if s == e else f"{s:03x}-{e:03x}" for s, e in out)


def table(name, res):
    print(f"== {name}")
    for p, (priv, mce, sce, addrs) in PASSES.items():
        missing = [a for a in addrs if (p << 16) | a not in res]
        rd = [a for a in addrs if (p << 16) | a in res and res[(p << 16) | a]["trap"] is None]
        wr = [a for a in addrs if (p << 16) | a | 0x1000 in res and res[(p << 16) | a | 0x1000]["trap"] is None]
        tag = f"pass {p} priv {'MSU'[[M, S, U].index(priv)]} mcounteren {mce} scounteren {sce}"
        print(f"  {tag}: read ok  {ranges(rd)}")
        print(f"  {tag}: write ok {ranges(wr)}")
        if missing:
            print(f"  {tag}: NOT REACHED {ranges(missing)}")
    for addr in WRBACK:
        w = res.get((7 << 16) | addr | 0x2000, {})
        r = res.get((7 << 16) | addr | 0x3000, {})
        wt = "trap %d" % w["trap"] if w.get("trap") is not None else "ok"
        rt = "trap %d" % r["trap"] if r.get("trap") is not None else "ok"
        rv = f"{r['val']:#x}" if r.get("val") is not None else "-"
        print(f"  write -1 to {addr:03x}: {wt}; read back: {rt} {rv}")


def main():
    raw = sys.argv[sys.argv.index("--raw") + 1] if "--raw" in sys.argv else None
    with tempfile.TemporaryDirectory() as d:
        src = Path(d) / "probe_csr.S"
        src.write_text(gen())
        elf = Path(d) / "probe_csr.elf"
        subprocess.run(["riscv64-unknown-elf-gcc", "-march=rv64imafdc_zicsr", "-mabi=lp64", "-nostdlib", "-mno-relax",
                        "-T", str(HERE / "probe_csr.ld"), "-o", str(elf), str(src)], check=True)
        for name, (cfg, ovr, zicntr) in CONFIGS.items():
            out = run(elf, cfg, ovr, zicntr, d)
            if raw == name:
                print(out)
            table(name, parse(out))


if __name__ == "__main__":
    main()
